GdVal native_original_ordered_nan_add(const GdVal& a,const GdVal& b) {
    double value=a.f;
#if defined(__GNUC__) && defined(__x86_64__)
    __asm__ volatile ("addsd %1, %0" : "+x"(value) : "x"(b.f) : "memory");
#else
    value = a.f + b.f;
#endif
    return GdVal::from_float(value);
}
GdVal native_original_ordered_nan_mul(const GdVal& a,const GdVal& b) {
    double value=a.f;
#if defined(__GNUC__) && defined(__x86_64__)
    __asm__ volatile ("mulsd %1, %0" : "+x"(value) : "x"(b.f) : "memory");
#else
    value = a.f * b.f;
#endif
    return GdVal::from_float(value);
}
