#include <stdio.h>
#include <stdint.h>
#include "aes256.h"

int main(){
    uint8_t key[32]={
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f};
    AES_ctx ctx; AES_init_ctx(&ctx,key);
    /* RoundKey is 240 bytes = 60 words of 4 bytes. Print words 0,1,2,3,4,5,6,7,8 */
    for(int w=0; w<=8; w++){
        printf("w[%2d] = ", w);
        for(int b=0;b<4;b++) printf("%02x", ctx.RoundKey[w*4+b]);
        printf("\n");
    }
    printf("expected: w[8]=a0fafe17 88542cb1 23a33939 2a6c7605\n");
    return 0;
}
